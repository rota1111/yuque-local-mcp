'use strict';
const assert=require('node:assert/strict');
const {locateSection,contentFragment}=require('./sections.cjs');
const prefix='<!doctype lake><meta name="doc-version" content="1" /><p>Intro</p>';
const heading='<h2 id="first"><strong>背景</strong> &amp; 目标</h2>';
const body='<p>Old</p><h3>Detail</h3><table><tr><td><h1>Embedded heading</h1></td></tr></table><card name="code" value="&lt;h1&gt;" />';
const suffix='<h2 id="next">下一节</h2><p>Keep</p><h1>End</h1>';
const lake=prefix+heading+body+suffix;
const section=locateSection(lake,'背景 & 目标');
assert.equal(lake.slice(section.start,section.end),body);
assert.equal(lake.slice(0,section.start),prefix+heading);
assert.equal(lake.slice(section.end),suffix);
assert.equal(contentFragment('<!doctype lake><meta name="doc-version" content="1" /><p>New</p><h3>New detail</h3>'),'<p>New</p><h3>New detail</h3>');
const last=locateSection(lake,'End');assert.equal(last.end,lake.length);assert.equal(last.start,lake.length);
assert.throws(()=>locateSection(lake,'Missing'),/未找到/);
assert.throws(()=>locateSection(lake,'Embedded heading'),/未找到/);
const duplicate='<!doctype lake><h2>Same</h2><p>A</p><h2>Same</h2><p>B</p>';
assert.throws(()=>locateSection(duplicate,'Same'),/同名/);
assert.equal(duplicate.slice(locateSection(duplicate,'Same',2).start),'<p>B</p>');
assert.throws(()=>locateSection(duplicate,'Same',3),/范围/);
assert.throws(()=>locateSection('<!doctype lake><h2>A</h2><p>Unclosed','A'),/结构/);
assert.throws(()=>locateSection('<!doctype lake><h2>A</h2><p></div>','A'),/不平衡/);
assert.throws(()=>contentFragment('<!doctype lake><p>Bad'),/结构/);
assert.equal(locateSection('<!doctype lake><h2>第&#x4e00;节</h2><p>x</p>','第一节').heading,'第一节');
assert.throws(()=>contentFragment('<!doctype lake><meta name="only" />'),/正文为空/);
assert.equal(locateSection('<!doctype lake><h2 data-x="a > b">Title</h2><p>Text</p>','Title').heading,'Title');
console.log('PASS: section boundaries, subheadings, embedded headings, duplicate selection, entities, malformed Lake and converted fragment');
